class JsonlLog:
    """Best-effort privacy-safe audit log.  Logging must never mask recovery."""
    def __init__(self, path: Path, *, machine_id: str | None = None) -> None:
        self.path, self.machine_id = Path(path), machine_id
    def write(self, state: WorkflowState, event: str, code: str | None = None, *, session_id: str | None = None, last_successful_state: WorkflowState | None = None, safe_oid: str | None = None, safe_root_hash: str | None = None, archive_root: str | None = None, quarantine_root: str | None = None, archive_id: str | None = None, quarantine_id: str | None = None, remote_check_status: str | None = None) -> None:
        # Values are allow-listed identifiers only; callers never pass paths or exception text.
        row: dict[str, str] = {"schema_version":"1.0.0", "timestamp_utc":datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00","Z"), "state":state.value, "event":event}
        if self.machine_id and re.fullmatch(r"[A-Za-z0-9._-]{1,128}",self.machine_id): row["machine_id"] = self.machine_id
        if session_id and re.fullmatch(r"[A-Za-z0-9._-]{1,128}",session_id): row["session_id"] = session_id
        if last_successful_state: row["last_successful_state"] = last_successful_state.value
        if safe_oid and re.fullmatch(r"[0-9a-f]{40}(?:[0-9a-f]{24})?",safe_oid): row["safe_oid"] = safe_oid
        if safe_root_hash and re.fullmatch(r"[0-9a-f]{64}",safe_root_hash): row["safe_root_hash"] = safe_root_hash
        if archive_root and re.fullmatch(r"[0-9a-f]{64}",archive_root): row["archive_root"] = archive_root
        if quarantine_root and re.fullmatch(r"[0-9a-f]{64}",quarantine_root): row["quarantine_root"] = quarantine_root
        # These are basename identifiers generated by us, never save-relative paths.
        if archive_id and re.fullmatch(r"save-[0-9TZ-]+-[0-9a-f]{16}-[0-9a-f]{32}", archive_id): row["archive_id"] = archive_id
        if quarantine_id and re.fullmatch(r"save-[0-9TZ-]+-[0-9a-f]{16}-[0-9a-f]{32}", quarantine_id): row["quarantine_id"] = quarantine_id
        # Only the check's own status; never a commit OID, root hash, path, or remote URL.
        if remote_check_status in ("ok", "failed", "skipped"): row["remote_check_status"] = remote_check_status
        if code:
            row["code"] = code
            row["next_command"] = "grim-dawn-sync status" if code in {"vault_not_reconciled","remote_main_missing","bootstrap_required"} else "grim-dawn-sync recover"
        self.path.parent.mkdir(parents=True, exist_ok=True)
        with self.path.open("a", encoding="utf-8", newline="\n") as out: out.write(json.dumps(row, sort_keys=True, separators=(",",":"))+"\n")


