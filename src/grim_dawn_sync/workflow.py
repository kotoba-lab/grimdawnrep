    def fetch_and_reconcile(self) -> Any: ...
    def remote_oid(self) -> str | None: ...
    def acquire(self, base: str, *, expected_pre_state: SyncState | None = None) -> Any: ...
    def prepare_remote_restore(self, base: str, session: str) -> Any: ...
    def archive_before_restore(self, plan: Any) -> Any: ...
    def apply_remote_save(self, plan: Any) -> Any: ...
    def launch(self, hook: Callable[[str], None]) -> Any: ...
    def wait_save_stable(self) -> dict: ...
    def validate(self, manifest: dict, baseline: dict | None) -> dict: ...
    def archive_after_game(self, manifest: dict) -> str: ...
    def rescue_raw(self, manifest: dict | None) -> str: ...
    def quarantine(self, manifest: dict) -> str: ...
    def snapshot(self, session: str, manifest: dict, hook: Callable[[str], None]) -> str: ...
